"""
Run the TWSMA analytics over the Adzuna jobs ALREADY SAVED in data/raw/. Makes NO API calls
and does not touch any database.

  python scripts/run_twsma_analysis.py            -> writes docs/twsma_analysis_report.md
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from backend.app.services import twsma_service as tw  # noqa: E402
from ingestion.normalizer import JobNormalizer  # noqa: E402
from nlp.skill_extractor import SkillExtractor  # noqa: E402

RAW_DIR = os.path.join(ROOT, "data", "raw")
OUT = os.path.join(ROOT, "docs", "twsma_analysis_report.md")


def load_latest_adzuna_records():
    files = sorted(glob.glob(os.path.join(RAW_DIR, "adzuna_raw_*_q*.json")))
    if not files:
        sys.exit("No Adzuna raw files in data/raw/")
    ts = max(re.search(r"adzuna_raw_(\d{8}_\d{6})_", os.path.basename(f)).group(1) for f in files)
    extractor, seen, records, collected = SkillExtractor(), set(), [], None
    for f in [f for f in files if f"adzuna_raw_{ts}_" in os.path.basename(f)]:
        with open(f, encoding="utf-8") as fh:
            rec = json.load(fh)
        collected = collected or rec.get("fetched_at")
        for raw in (rec.get("response") or {}).get("results", []):
            norm = JobNormalizer.normalize_adzuna_record(raw)
            if norm is None or norm.job_id in seen:
                continue
            seen.add(norm.job_id)
            text = f"{norm.title} {norm.description_cleaned or norm.description}"
            records.append(tw.JobRecord(
                title=norm.title, role_category=norm.role_category, company=norm.company_name,
                city=norm.city, description=norm.description_cleaned or norm.description,
                posted_at=norm.posted_at, skills=sorted({s.name for s in extractor.extract_skills(text)}),
                salary_min=norm.salary_min, salary_max=norm.salary_max,
                role_is_fallback=tw.role_is_fallback(norm.title, norm.role_category)))
    return records, collected


def table(rows, headers):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(" :--- " for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    records, collected = load_latest_adzuna_records()
    rep = tw.build_twsma_report(records)
    deduped = tw.build_twsma_report(tw.dedupe_content(records))
    L = []
    w = L.append
    w("# TWSMA Analytics Report (real saved Adzuna data)\n")
    w(f"Generated by `scripts/run_twsma_analysis.py` from `data/raw/` (no API calls). Collected: {collected}.\n")
    w(f"Jobs analysed: **{rep['total_jobs']}** (unique Adzuna IDs). After dropping likely reposts "
      f"(same title+company+city): **{deduped['total_jobs']}**.\n")
    w("> Scope caveat: the four Adzuna queries were Data Analyst / Data Scientist in Mumbai, Bengaluru, Pune, "
      "Hyderabad (20 jobs each). Role, location and skill shares describe THIS sample, not the Indian job market.\n")

    c = rep["skill_coverage"]
    w("## 1. Top skills\n")
    w(f"Jobs with >=1 extracted skill: {c['jobs_with_skills']}/{c['total_jobs']} ({c['coverage_percentage']}%); "
      f"mean {c['mean_skills_per_job']} skills/job. Percentages are of all {c['total_jobs']} jobs.\n")
    w(table([(s["skill"], s["job_count"], f"{s['percentage']}%") for s in rep["top_skills"]],
            ["Skill", "Jobs", "% of jobs"]))
    def top5_str(rp):
        return ", ".join(f"{s['skill']} {s['job_count']}" for s in rp["top_skills"][:5])
    w(f"\nTop-5 with all {rep['total_jobs']} jobs: {top5_str(rep)}.  "
      f"After content de-duplication ({deduped['total_jobs']} jobs): {top5_str(deduped)}.  "
      "(Differences at equal counts are tie-breaks.)\n")

    w("## 2. Role distribution\n")
    rd = rep["role_distribution"]
    w(f"Keyword-classified: {rd['classified_by_keyword']}; unmatched (fell back to default category): "
      f"{rd['unmatched_fallback']}.\n")
    w(table([(i["role_category"], i["job_count"], f"{i['percentage']}%", i["fallback_count"]) for i in rd["items"]],
            ["Role", "Jobs", "%", "of which unmatched fallback"]))

    w("\n## 3. Skills by role (top 5; % of that role's jobs)\n")
    for role, d in rep["skills_by_role"].items():
        sk = ", ".join(f"{s['skill']} {s['job_count']} ({s['percentage']}%)" for s in d["top_skills"][:5]) \
            or "none extracted"
        w(f"- **{role}** ({d['job_count']} jobs, {d['jobs_with_skills']} with skills): {sk}")

    w("\n## 4. Locations\n")
    w(table([(i["city"], i["job_count"], f"{i['percentage']}%") for i in rep["location_distribution"]["items"]],
            ["City", "Jobs", "%"]))
    w("\nTop skills per city (% of that city's jobs):\n")
    for city, d in rep["skills_by_location"].items():
        sk = ", ".join(f"{s['skill']} {s['percentage']}%" for s in d["top_skills"][:5])
        w(f"- **{city}** ({d['job_count']} jobs): {sk}")
    w("\nRole mix per city:\n")
    for city, items in rep["roles_by_location"].items():
        w(f"- **{city}**: " + ", ".join(f"{i['role_category']} {i['job_count']}" for i in items))

    w("\n## 5. Companies\n")
    cd = rep["company_distribution"]
    w(f"{cd['distinct_companies']} distinct disclosed companies; {cd['undisclosed_count']} postings with "
      "undisclosed company.\n")
    w(table([(i["company"], i["job_count"]) for i in cd["items"][:10]], ["Company", "Postings"]))

    w("\n## 6. Skill co-occurrence (pairs in >=2 jobs)\n")
    w(table([(f"{p['skill_a']} + {p['skill_b']}", p["job_count"], f"{p['percentage']}%", p["lift"])
             for p in rep["skill_cooccurrence"][:15]], ["Pair", "Jobs", "% of jobs", "Lift"]))

    ta = rep["text_analysis"]
    d = ta["description"]
    w("\n## 7. Text / description analysis\n")
    w(f"- Descriptions: missing {d['missing_description']}; length mean {d['mean_length']}, median "
      f"{d['median_length']}, min {d['min_length']}, max {d['max_length']} chars; "
      f"{d['truncated_with_ellipsis']}/{d['total_jobs']} end in an ellipsis (Adzuna snippet cap).")
    q = ta["qualifications"]
    w(f"- Qualification mentions: {q['jobs_with_any_qualification']}/{q['total_jobs']} jobs: "
      + (", ".join(f"{i['qualification']} {i['job_count']}" for i in q["items"]) or "none"))
    e = ta["experience"]
    w(f"- Experience stated in text: {e['jobs_with_stated_experience']}/{e['total_jobs']} jobs "
      f"({e['coverage_percentage']}%), {e['with_upper_bound']} with an upper bound; median minimum "
      f"{e['median_min_years']} years (inferred from text; the API supplies none).")
    w("- Common terms (jobs containing): "
      + ", ".join(f"{t['term']} {t['job_count']}" for t in ta["common_terms"]["unigrams"][:15]))
    w("- Common bigrams: "
      + ", ".join(f"{t['term']} {t['job_count']}" for t in ta["common_terms"]["bigrams"][:12]))

    p = rep["posting_dates"]
    w("\n## 8. Posting dates / trend\n")
    w(f"Dates present {p['with_date']}/{p['total_jobs']}; range {p['earliest']} to {p['latest']}.")
    if "freshness" in p:
        w("Age relative to " + p["freshness_reference"] + " (latest posting): "
          + ", ".join(f"{k}: {v}" for k, v in p["freshness"].items()) + ".")
    w(f"\n**Trend analysis supported: {p['trend_supported']}.** {p.get('trend_reason', '')} {p['caveat']}")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")
    print("Report written:", OUT, "| jobs:", rep["total_jobs"])


if __name__ == "__main__":
    main()
