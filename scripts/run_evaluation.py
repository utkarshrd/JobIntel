"""
Reproducible offline recommender evaluation over the Adzuna jobs ALREADY SAVED in data/raw/.
Makes NO API calls and does not touch any database.

  python scripts/run_evaluation.py [--seeds 50]
    -> writes docs/evaluation_results.json and docs/evaluation_report.md

Relevance is a PROXY (Adzuna query membership), not user feedback. See recommender/evaluation.py.
"""
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from recommender import evaluation as ev  # noqa: E402
from recommender.config import weights_for_strategy  # noqa: E402

RAW_DIR = os.path.join(ROOT, "data", "raw")
OUT_JSON = os.path.join(ROOT, "docs", "evaluation_results.json")
OUT_MD = os.path.join(ROOT, "docs", "evaluation_report.md")

LABELS = {"popularity": "Popularity (recency)", "skills": "Skill-based", "content": "TF-IDF content",
          "hybrid": "Hybrid", ev.RANDOM_REFERENCE: "Random (reference only)"}
SCENARIO_TITLES = {
    "query": "Scenario A - persona = (search role, city); profile has role + location + seed-derived skills",
    "role": "Scenario B - persona = search role only; profile has role + seed-derived skills, NO location",
}


def f(x):
    return "n/a" if x is None else f"{x:.3f}"


def results_table(summary, k):
    rows = ["| Model | Precision@%d | Recall@%d | NDCG@%d | Diversity@%d |" % (k, k, k, k), "|:---|---:|---:|---:|---:|"]
    for name in list(ev.STRATEGIES) + [ev.RANDOM_REFERENCE]:
        s = summary[name]
        cells = [f"{f(s[f'{m}@{k}']['mean'])} ± {f(s[f'{m}@{k}']['std'])}" for m in ("precision", "recall", "ndcg", "diversity")]
        rows.append(f"| {LABELS[name]} | " + " | ".join(cells) + " |")
    return "\n".join(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=50)
    ap.add_argument("--run", help="collection timestamp in data/raw (default: latest). The original Phase D run is 20260930_190411")
    ap.add_argument("--taxonomy", help="skills taxonomy JSON (default: current). Phase D used nlp/dictionaries/skills_taxonomy_v1.json")
    ap.add_argument("--tag", default="", help="suffix for the output files, e.g. v1 -> docs/evaluation_report_v1.md")
    args = ap.parse_args()
    n_seeds = args.seeds
    global OUT_JSON, OUT_MD
    if args.tag:
        OUT_JSON = OUT_JSON.replace(".json", f"_{args.tag}.json")
        OUT_MD = OUT_MD.replace(".md", f"_{args.tag}.md")
    jobs = ev.load_saved_adzuna(RAW_DIR, taxonomy_path=args.taxonomy, run_ts=args.run)
    res = ev.evaluate(jobs, n_seeds=n_seeds)
    res["dataset"] = {"run": args.run or "latest", "taxonomy": args.taxonomy or "current"}
    # The behavior signal is inactive here (profiles are built from seed jobs; there are no interactions),
    # so it is dropped and the others renormalised exactly as rank_jobs does.
    raw = {k: v for k, v in weights_for_strategy("hybrid").as_dict().items() if k != "behavior"}
    res["hybrid_weights_normalised_default"] = {k: v / sum(raw.values()) for k, v in raw.items()}
    with open(OUT_JSON, "w", encoding="utf-8") as fh:
        json.dump(res, fh, indent=2)

    L, w = [], None
    w = L.append
    w("# Recommender Evaluation Report (offline proxy evaluation)\n")
    w("Generated by `scripts/run_evaluation.py` from the saved Adzuna files in `data/raw/` (no API calls, no database). "
      f"Jobs after dropping content reposts: **{res['n_jobs']}**. Random splits per persona: **{n_seeds}** (seeds 0..{n_seeds - 1}).\n")
    w("> **This is NOT an evaluation against user feedback.** The project has zero users and zero interactions. "
      "Relevance below is a proxy derived from which Adzuna search returned a job. Numbers say how well each strategy "
      "recovers held-out jobs from the same search as a persona's seed jobs - nothing more.\n")
    w("## Methodology\n")
    w("1. **Persona** = one collection query in `data/raw/` (e.g. Data Analyst / Mumbai). Its **relevant set** is the jobs Adzuna returned for it "
      "(Scenario A) or for every query with the same search role (Scenario B).\n"
      "2. The relevant set is split at random into **seed jobs** (stand-in for history) and **held-out jobs** (the labels). Seed jobs are removed from the candidate pool.\n"
      f"3. The **profile is built from seed jobs only**, by a fixed rule decided before running: skills present in >= {ev.SKILL_MIN_SEED_JOBS} seed jobs; "
      "target role = search role; location = search city (Scenario A only); profile text = role + skill names (the same recipe as `profile_from_user`).\n"
      "4. Each strategy ranks the candidate pool with the **production ranking code** (`recommender.ranking.rank_jobs`) and default weights "
      f"(hybrid normalised: {', '.join(f'{k} {v:.2f}' for k, v in res['hybrid_weights_normalised_default'].items())}). "
      "Weights were NOT tuned on these results.\n"
      "5. Metrics (binary relevance): Precision@K, Recall@K (denominator = held-out relevant jobs), NDCG@K, and **Diversity@K** = 1 - mean pairwise TF-IDF cosine "
      "similarity of job texts in the top K (higher = more varied lists; it measures variety, not quality).\n"
      "6. Values are **mean ± std over all (persona x seed) trials**. Trials from one persona are not independent.\n"
      "7. **Random** is a sanity floor, not a fifth strategy.\n"
      "8. **Winner rule (fixed in advance):** a strategy is a clear winner only if it has the highest mean NDCG@10 of the four, "
      "is ahead of every other strategy in every persona, and the 95% paired-bootstrap CI of its advantage over the runner-up excludes 0. "
      "Otherwise: no clear winner.\n")
    for sc, title in SCENARIO_TITLES.items():
        d = res["scenarios"][sc]
        w(f"## {title}\n")
        w("Personas: " + "; ".join(f"{n} ({v['n_relevant']} relevant jobs, mean {f(v['mean_profile_skills'])} profile skills, "
                                   f"{v['trials_without_skills']}/{n_seeds} trials with no profile skills)" for n, v in d["personas"].items()) + "\n")
        for k in ev.KS:
            w(f"### K = {k}\n")
            w(results_table(d["summary"], k) + "\n")
        w("Per-persona mean NDCG@10:\n")
        names = list(ev.STRATEGIES) + [ev.RANDOM_REFERENCE]
        w("| Persona | " + " | ".join(LABELS[n] for n in names) + " |")
        w("|:---|" + "---:|" * len(names))
        for pn, row in d["persona_ndcg@10"].items():
            w(f"| {pn} | " + " | ".join(f(row[n]) for n in names) + " |")
        wins = {n: sum(1 for pm in d["persona_ndcg@10"].values() if max(ev.STRATEGIES, key=lambda s: pm[s]) == n)
                for n in ev.STRATEGIES}
        w("\nSupplementary (NOT the verdict rule): personas where each strategy has the highest NDCG@10 of the four: "
          + ", ".join(f"{LABELS[n]} {c}/{len(d['persona_ndcg@10'])}" for n, c in wins.items()) + ".")
        w("\nCatalogue coverage@10 (share of all jobs that appear in some top-10): "
          + ", ".join(f"{LABELS[n]} {d['catalog_coverage@10'][n]:.0%}" for n in names) + ".\n")
        v = d["verdict"]
        w(f"**Verdict:** best mean NDCG@10 = {LABELS[v['leader']]} ({f(v['leader_mean_ndcg@10'])}) vs runner-up {LABELS[v['runner_up']]} "
          f"({f(v['runner_up_mean_ndcg@10'])}); ahead in every persona: {v['ahead_in_every_persona']}; "
          f"95% CI of the difference: [{v['ci95_vs_runner_up'][0]:.3f}, {v['ci95_vs_runner_up'][1]:.3f}]. "
          + (f"**Clear winner: {LABELS[v['clear_winner']]}.**" if v["clear_winner"] else "**No clear winner under the rule.**") + "\n")
    ov = res["overall_verdict"]
    w("## Overall conclusion\n")
    w((f"**{LABELS[ov['clear_winner']]}** " if ov["clear_winner"] else "**No clear winner.** ") + ov["note"] + "\n")
    w("## Limitations\n")
    w("- **Proxy, not feedback.** Relevance = \"Adzuna returned this job for the persona's search\". It is not a judgement that a job suits a person. "
      "No real or synthetic user preferences are used or claimed.\n"
      "- **Circularity.** The query defines both the persona's role/location and the relevance label. In Scenario A, location is a near-perfect label proxy "
      "(each persona's relevant jobs are all in one city), so any location-aware strategy is advantaged and the Hybrid result partly reflects that. "
      "Scenario B removes location to reduce this, but role words still drive both profile and label.\n"
      "- **Skill signal is weak and partly leaked.** Profile skills come from seed jobs of the same query, so skill overlap measures similarity to those jobs. "
      "Only ~1.7 skills are extracted per job (short snippets), so Skill-based ranks many jobs with a score of 0 and falls back to id order.\n"
      "- **Tiny, narrow data.** ~75 deduplicated jobs, 4 queries (Data Analyst in Mumbai/Pune, Data Scientist in Bengaluru/Hyderabad; no other roles). "
      "Only 2 (Scenario B) or 4 (Scenario A) personas; repeating 50 random splits reduces split noise, NOT persona-sample size, so the CI understates uncertainty about generalisation.\n"
      "- **Popularity is not personalised** and is only a recency percentile (no interaction counts exist), so it is a weak baseline by construction.\n"
      "- **Content signal and the label share vocabulary** (job titles contain the search role), another source of circularity.\n"
      "- **Diversity** is text-similarity based and is a property of the list, not its accuracy.\n"
      "- **Behavioral personalization is NOT evaluated.** The project has zero real interactions, so the behavior signal is inactive here "
      "(dropped and the other weights renormalised); no claim is made about interaction-informed ranking quality.\n"
      "- Results describe this collected sample only, not the Indian job market.\n")
    with open(OUT_MD, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")
    print(open(OUT_MD, encoding="utf-8").read())


if __name__ == "__main__":
    main()
